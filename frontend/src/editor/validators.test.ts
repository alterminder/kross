// @vitest-environment node
import { readFileSync, writeFileSync } from "node:fs";
import { getFirstMatchingOption, schemaParser, type RJSFSchema } from "@rjsf/utils";
import validator from "@rjsf/validator-ajv8";
import { compileSchemaValidatorsCode } from "@rjsf/validator-ajv8/compileSchemaValidators";
import { expect, test } from "vitest";
import { formSchemaOf, validatorFor } from "./formSchema";
import validators from "./validators.gen";

const served = JSON.parse(
  readFileSync(new URL("../../../backend/src/nlab/engine/schema/negotiation-scenario.v2.schema.json", import.meta.url), "utf8"),
);
const schema = formSchemaOf({ ...served, "x-skills-vocabulary": ["Context analysis"] });

test("the precompiled validators cover the backend's scenario schema (npm run validators regenerates them)", () => {
  if (process.env.UPDATE_VALIDATORS) {
    // unicode: false keeps ajv's ucs2length runtime import out: lengths count UTF-16 units, fine for branch matching
    const code = compileSchemaValidatorsCode(schema, { ajvOptionsOverrides: { unicode: false } }).replace('"use strict";', "");
    const header = "// @ts-nocheck\n// Generated by `npm run validators` from the backend's scenario schema: do not edit.\nconst exports = {};\n";
    writeFileSync(new URL("./validators.gen.ts", import.meta.url), `${header}${code}\nexport default exports;\n`);
    return;
  }
  expect(Object.keys(validators).sort()).toEqual(Object.keys(schemaParser(schema)).sort());
});

test("a confidential term's object form is told apart from its plain-text form without runtime compiling", () => {
  const precompiled = validatorFor(schema);
  expect(precompiled).not.toBe(validator);
  const multiparty = schema.properties!.multiparty as RJSFSchema;
  const options = ((multiparty.properties!.confidential_between as RJSFSchema).items as RJSFSchema).oneOf as RJSFSchema[];
  expect(getFirstMatchingOption(precompiled, { term: "fuel", between: ["a", "b"] }, options, schema)).toBe(1);
  expect(getFirstMatchingOption(precompiled, "fuel", options, schema)).toBe(0);
});

test("a schema this build does not know gets the runtime validator instead of throwing", () => {
  expect(validatorFor({ ...schema, title: "a newer schema" })).toBe(validator);
});
